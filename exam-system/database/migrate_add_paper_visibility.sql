-- ============================================================
-- 试卷可见性改造：教师创建试卷可选择对其他教师可见
-- 执行方式：在 MySQL 中对 exam_system 库执行本脚本一次
-- ============================================================

-- 试卷可见教师ID列表（逗号分隔的用户ID字符串，如 "3,5,8"）
-- NULL 或空串 = 仅创建人可见（默认，兼容历史数据）
-- 管理员不受此限制，始终可见全部试卷
ALTER TABLE exam_paper
    ADD COLUMN visible_user_ids VARCHAR(500) DEFAULT NULL
        COMMENT '可见教师ID列表（逗号分隔，NULL=仅创建者可见）' AFTER creator_id;
